// The runner: the two prompts and the record's frontmatter for one skill on
// one fixture, generated from the tree so they are current by construction.
// Prompt one frames the skill, its references and the ask; prompt two frames
// the reading; the frontmatter carries the three shas filled and the rest as
// placeholders. Each part is a fenced block, so a repository page renders a
// copy button on it and a phone can carry it. The runner reads files and
// returns text; it never calls a model.
import { readFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileSha } from "./sha.mjs";

const LINE = "==========";
const FRAMING = `The text between the lines is your instruction for this conversation. Read all of it before you answer. Do not search the web, do not name or open any repository, do not offer to create files or issues; answer the ask at the end in full, in one message, and ask me a question only where the instruction says to ask.`;
const READING = `You read an output against a checklist. Answer with one word on the first line, pass or flag, then one line per checklist item saying met or not met and why. Read only the checklist below; do not search the web and do not read any other copy of it.`;

// A fence one backtick longer than any run inside the text, so a skill that
// carries fences of its own still renders as one block with one copy button.
const fence = (text) => {
  const longest = Math.max(
    2,
    ...[...text.matchAll(/`+/g)].map((m) => m[0].length),
  );
  const f = "`".repeat(longest + 1);
  return `${f}text\n${text.trimEnd()}\n${f}`;
};

const references = (dir) =>
  existsSync(dir) && statSync(dir).isDirectory()
    ? readdirSync(dir)
        .filter((f) => statSync(join(dir, f)).isFile())
        .sort()
    : [];

/** Where the runner lives: beside the fixture's ask and expect. */
export function runnerPath(root, skill, fixture) {
  return join(root, "skills", skill, "fixtures", fixture, "RUNNER.md");
}

/** @returns {string} one markdown document, three fenced blocks */
export function renderRunner(root, skill, fixture) {
  const s = join(root, "skills", skill);
  const fx = join(s, "fixtures", fixture);
  const skillMd = join(s, "SKILL.md");
  const askMd = join(fx, "ask.md");
  const expectMd = join(fx, "expect.md");
  for (const f of [skillMd, askMd, expectMd])
    if (!existsSync(f)) throw new Error(`runner: ${f} does not exist`);
  const refs = references(join(s, "references")).map(
    (f) =>
      `---- references/${f} ----\n${readFileSync(join(s, "references", f), "utf8").trimEnd()}`,
  );
  const one = [
    FRAMING,
    LINE,
    readFileSync(skillMd, "utf8").trimEnd(),
    ...refs,
    LINE,
    readFileSync(askMd, "utf8").trimEnd(),
  ].join("\n\n");
  const items = readFileSync(expectMd, "utf8")
    .split(/\r?\n/)
    .filter((l) => /^(- |  )/.test(l))
    .join("\n");
  const two = `${READING}\n\nChecklist:\n${items}\n\nOutput:`;
  const three = [
    "---",
    "model: <provider and id>",
    "reader: <the model that read the output>",
    "temperature: <the sampling temperature, or default>",
    "date: <YYYY-MM-DD>",
    `fixture: ${fixture}`,
    `ask_sha: ${fileSha(askMd)}`,
    `expect_sha: ${fileSha(expectMd)}`,
    `skill_sha: ${fileSha(skillMd)}`,
    "setup: <chat, system, workspace or workflow>",
    "verdict: <pass or flag, the reading's first word>",
    "---",
  ].join("\n");
  return (
    [
      `<!-- generated by kaal runner ${skill} ${fixture}; edit the skill or the fixture, then regenerate -->`,
      `# Runner: ${skill} on ${fixture}`,
      `Three blocks, each with a copy button on the repository page. Send the first as one message in a fresh conversation, in the setup the record will name. Paste the whole exchange, first line to last, your own answers included, after the second block's last line and send it as a fresh message. Fill the third block in, then the two sections, and file it as \`evals/${skill}/${fixture}/<model>.md\`.`,
      "## Prompt 1: the skill and the ask",
      fence(one),
      "## Prompt 2: the reading",
      fence(two),
      "## The record's frontmatter",
      fence(three),
    ].join("\n\n") + "\n"
  );
}
